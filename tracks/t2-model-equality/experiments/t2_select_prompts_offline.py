"""T2: offline prompt-selection using nuisance-robust conditional logit differences.

NO competition endpoint calls.  Use LOCAL twin-model logits and a fixed bank
of candidate prompts. Each context is a continuation generated by the local
base model, not a Wikipedia/prompt token. Score prompts whose distributions
still differ from pseudo-LoRA/fp8 models after allowing different temperature
and nucleus top_p settings for each deployment.

Input:
  npz: base_logits [P,S,V] (or [P,V]), variant_logits [P,M,S,V]
       (or [P,M,V]), optional prompts [P] strings.
All logits share the SAME vocabulary and SAME token prefixes at each S.
Model variants should include *multiple seeds* of weak LoRA, strong LoRA,
and fp8. Do not train a variant on a heldout test prompt.

Usage:
 python t2_select_prompts_offline.py --cache local_twins.npz --out ranking.csv
 python t2_select_prompts_offline.py  # synthetic CPU self-test
"""
import argparse
import csv
import numpy as np


def softmax(x, temperature, top_p):
    x = np.asarray(x, np.float64) / temperature
    x = x - np.max(x, axis=-1, keepdims=True)
    p = np.exp(x)
    p /= np.maximum(p.sum(axis=-1, keepdims=True), 1e-300)
    if top_p < 1:
        order = np.argsort(-p, axis=-1)
        v = np.take_along_axis(p, order, axis=-1)
        keep = (np.cumsum(v, axis=-1) - v) < top_p
        kept = np.where(keep, v, 0.)
        p = np.zeros_like(p)
        np.put_along_axis(p, order, kept, axis=-1)
        p /= np.maximum(p.sum(axis=-1, keepdims=True), 1e-300)
    return p


def jsd(p, q):
    m = (p + q) * 0.5
    return .5 * np.sum(np.where(p > 0, p * np.log(np.maximum(p, 1e-300)
                                                  / np.maximum(m, 1e-300)), 0), axis=-1) + \
           .5 * np.sum(np.where(q > 0, q * np.log(np.maximum(q, 1e-300)
                                                  / np.maximum(m, 1e-300)), 0), axis=-1)


def rank_prompts(base, variants, temperatures=(.6, .8, 1., 1.2),
                 top_ps=(.95, 1.)):
    base = np.asarray(base, dtype=np.float32)
    variants = np.asarray(variants, dtype=np.float32)
    if base.ndim == 2:
        base = base[:, None, :]
    if variants.ndim == 3:
        variants = variants[:, :, None, :]
    if base.ndim != 3 or variants.ndim != 4:
        raise ValueError('Expected base [P,S,V] variants [P,M,S,V]')
    P, S, V = base.shape
    if variants.shape[0] != P or variants.shape[2:] != (S, V) or V < 3 or S < 1 or P < 1:
        raise ValueError('Misaligned shape, context or tokenizer')
    if not (np.isfinite(base).all() and np.isfinite(variants).all()):
        raise ValueError('Logits must be finite')
    M = variants.shape[1]
    if M == 0:
        raise ValueError('Need >=1 simulated variant')
    if any(t <= 0 for t in temperatures) or any(p <= 0 or p > 1 for p in top_ps):
        raise ValueError('Invalid sampling grid')

    scores = []
    for i in range(P):
        b = base[i]
        bp = [softmax(b, t, nu) for t in temperatures for nu in top_ps]
        var_robust = []
        inv_count = []
        best2 = np.argsort(-b, axis=-1)[:, :2]
        for j in range(M):
            v = variants[i, j]
            vp = [softmax(v, t, nu) for t in temperatures for nu in top_ps]
            # Same paired contexts: seek the closest nuisance-adjusted distributions.
            d = min(float(jsd(x, y).mean()) for x in bp for y in vp)
            var_robust.append(d)
            vi = np.take_along_axis(v, best2, axis=-1)
            inv_count.append(float((vi[:, 0] < vi[:, 1]).mean()))
        robust = float(np.quantile(var_robust, .25))
        flip = float(np.mean(inv_count))
        scores.append((i, robust * (1. + .25 * flip), robust,
                       float(np.mean(var_robust)), flip))
    return sorted(scores, key=lambda x: -x[1])


def smoke_test():
    rng = np.random.default_rng(22)
    b = rng.normal(size=(4, 12)).astype('float32')
    b[0] = np.array([5, 4] + [0] * 10)
    b[1] = b[0]
    b[2] = b[0]
    b[3] = b[0]
    v = np.stack([b.copy() for _ in range(3)], axis=1)
    # Temperature-only change is not evidence of new weights.
    v[0] *= 1.5
    # Real rank ordering changes under variant, not explainable by temperature.
    v[1, :, 0] = 1
    v[1, :, 1] = 5
    # Constant logit shift is invisible to softmax.
    v[2] += 3.
    # One unstable pseudo variant alone must not dominate 25th percentile.
    v[3, 0, 0] = 1
    v[3, 0, 1] = 5
    out = rank_prompts(b, v, top_ps=(1.,))
    assert out[0][0] == 1, out
    assert next(x for x in out if x[0] == 2)[1] < 1e-10, out
    assert next(x for x in out if x[0] == 0)[1] < 1e-9, out
    print('PASS: rank-sensitive prompts prioritized; temperature-only and offset controls near zero')


def main():
    a = argparse.ArgumentParser(description=__doc__)
    a.add_argument('--cache', help='NPZ generated entirely by local twin models')
    a.add_argument('--out', default='t2_prompt_ranking.csv')
    args = a.parse_args()
    if not args.cache:
        smoke_test()
        return
    data = np.load(args.cache, allow_pickle=False)
    ranked = rank_prompts(data['base_logits'], data['variant_logits'])
    prompts = data['prompts'] if 'prompts' in data else None
    with open(args.out, 'w', newline='', encoding='utf-8') as f:
        w = csv.writer(f)
        w.writerow(['prompt_index', 'robust_score', 'q25_jsd', 'mean_jsd',
                    'top2_flip', 'prompt'])
        for i, score, robust, mean, flip in ranked:
            w.writerow([i, score, robust, mean, flip,
                        str(prompts[i]) if prompts is not None else ''])
    print('Wrote', len(ranked), 'ranked local prompts to', args.out,
          'No EAC API calls. Calibrate on held-out ref/twins before using any ep query.')


if __name__ == '__main__':
    main()
