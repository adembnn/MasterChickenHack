"""T2 robust private-MCC scenario evaluator (offline only).

Given posterior hypotheses generated by Adem's existing T2 audit, compare
candidate CSVs on public vs HELDOUT endpoint pairs. No EAC API calls.
Note: the public split mechanism and which file counts for final are UNKNOWN.

Input hypotheses.json:
  {"scenarios":[
    {"truth_csv":"truth1.csv","public_endpoints":["ep-01","ep-02",...],"weight":1},
    {"truth_csv":"truth2.csv","public_pairs":["ep-01|ep-02",...],"weight":1}
  ]}
Relative truth CSV paths resolve relative to hypotheses.json.
Outputs posterior expected hidden MCC, 10th percentile, and probability of
beating baseline on hidden. These are CONDITIONAL ON USER-SUPPLIED SCENARIOS,
not actual hidden scores, and MUST NOT be optimized on leaderboard alone.

python t2_private_robust_score.py --smoke
python t2_private_robust_score.py --scenarios hypotheses.json \
 --baseline t2_1967.csv --candidates cand_ep26.csv cand_full.csv
"""
import argparse
import csv
import json
from pathlib import Path
import numpy as np


def read_partition(path):
    with open(path, newline='', encoding='utf8') as fp:
        rows = list(csv.DictReader(fp))
    if not rows or set(rows[0]) != {'endpoint', 'family', 'model'}:
        raise ValueError(f'{path}: need endpoint,family,model CSV')
    out = {}
    for row in rows:
        ep, fam, model = (row[k].strip() for k in ('endpoint', 'family', 'model'))
        if not ep or not fam or not model or ep in out:
            raise ValueError(f'{path}: missing field or duplicate endpoint')
        out[ep] = (fam, model)
    return out


def mcc(yt, yp):
    yt = np.asarray(yt, bool)
    yp = np.asarray(yp, bool)
    tp = int(np.sum(yt & yp))
    tn = int(np.sum(~yt & ~yp))
    fp = int(np.sum(~yt & yp))
    fn = int(np.sum(yt & ~yp))
    den = ((tp + fp)*(tp + fn)*(tn + fp)*(tn + fn))**.5
    return 0. if den == 0 else (tp*tn - fp*fn)/den


def pair_score(truth, predicted, pairs):
    """Exact EAC form: family MCC all pairs; model MCC true-family pairs."""
    tf, pf, tm, pm = [], [], [], []
    for a, b in pairs:
        samefam = truth[a][0] == truth[b][0]
        tf.append(samefam)
        pf.append(predicted[a][0] == predicted[b][0])
        if samefam:
            tm.append(truth[a] == truth[b])
            pm.append(predicted[a] == predicted[b])
    return .1*max(0., mcc(tf, pf)) + .9*max(0., mcc(tm, pm))


def make_pairs(truth, scenario):
    keys = sorted(truth)
    allpairs = [(keys[i], keys[j]) for i in range(len(keys))
                for j in range(i + 1, len(keys))]
    if 'public_pairs' in scenario:
        ps = set()
        for pair in scenario['public_pairs']:
            v = pair.split('|') if isinstance(pair, str) else pair
            if len(v) != 2 or v[0] == v[1] or v[0] not in truth or v[1] not in truth:
                raise ValueError(f'bad public pair: {pair}')
            ps.add(tuple(sorted(v)))
        public = [p for p in allpairs if p in ps]
    elif 'public_endpoints' in scenario:
        ids = set(scenario['public_endpoints'])
        if not ids <= set(truth):
            raise ValueError('unknown public endpoint')
        public = [p for p in allpairs if p[0] in ids and p[1] in ids]
    else:
        raise ValueError('need public_pairs or public_endpoints')
    ps = set(public)
    hidden = [p for p in allpairs if p not in ps]
    if not public or not hidden:
        raise ValueError('public or hidden pairs empty')
    return {'public': public, 'hidden': hidden, 'full': allpairs}


def weighted_quantile(values, weights, q):
    i = np.argsort(values)
    v = np.asarray(values)[i]
    w = np.asarray(weights)[i]
    return float(v[np.searchsorted(np.cumsum(w), q, side='left').clip(0, len(v)-1)])


def evaluate(scenario_path, baseline, candidate_paths):
    path = Path(scenario_path)
    scenes = json.loads(path.read_text(encoding='utf8'))['scenarios']
    if not scenes:
        raise ValueError('No scenarios')
    parts = {'BASELINE': read_partition(baseline)}
    for cp in candidate_paths:
        parts[Path(cp).name] = read_partition(cp)
    scored = []
    for scen in scenes:
        f = Path(scen['truth_csv'])
        truth = read_partition(f if f.is_absolute() else path.parent / f)
        if not all(set(x) == set(truth) for x in parts.values()):
            raise ValueError('Candidate endpoint IDs differ from truth')
        w = float(scen.get('weight', 1))
        if not np.isfinite(w) or w <= 0:
            raise ValueError('Invalid posterior weight')
        pair_sets = make_pairs(truth, scen)
        row = {name: {split: pair_score(truth, part, pairs)
                      for split, pairs in pair_sets.items()}
               for name, part in parts.items()}
        scored.append((w, row))
    weights = np.array([x[0] for x in scored], float)
    weights /= weights.sum()
    b = np.array([x[1]['BASELINE']['hidden'] for x in scored])
    result = {}
    for name in parts:
        hidden = np.array([x[1][name]['hidden'] for x in scored])
        public = np.array([x[1][name]['public'] for x in scored])
        delta = hidden - b
        result[name] = {
          'E_public_conditional': float(public @ weights),
          'E_hidden_conditional': float(hidden @ weights),
          'hidden_q10': weighted_quantile(hidden, weights, .10),
          'hidden_q50': weighted_quantile(hidden, weights, .50),
          'E_hidden_gain_vs_baseline': float(delta @ weights),
          'P_hidden_gain': float(weights[delta > 1e-8].sum()),
          'P_hidden_no_worse': float(weights[delta >= -1e-8].sum())
        }
    return {'WARNING': 'Posterior hypotheses, NOT hidden truth; scenario prior quality dominates.',
            'scenarios': len(scored), 'candidates': result}


def smoke():
    truth = {f'e{i}': ('F1', 'A' if i <= 3 else 'B') for i in range(1, 5)}
    truth.update({f'e{i}': ('F2', 'C' if i <= 6 else 'D')
                  for i in range(5, 9)})
    truth.update({'e9': ('F3', 'E'), 'e10': ('F3', 'E'),
                  'e11': ('F3', 'F'), 'e12': ('F3', 'F')})
    pairs = make_pairs(truth, {'public_endpoints': [f'e{i}' for i in range(1, 11)]})
    assert all(abs(pair_score(truth, truth, p)-1) < 1e-12
               for p in pairs.values())
    bad = dict(truth)
    bad['e2'] = ('F1', 'B')
    assert pair_score(truth, bad, pairs['full']) < 1
    assert pair_score(truth, bad, pairs['public']) < 1
    assert mcc([True, True], [True, True]) == 0
    assert abs(weighted_quantile([.1, .9], [.2, .8], .5)-.9) < 1e-12
    print('PASS synthetic: exact/incorrect partitions, public/hidden, MCC, weighted quantiles')


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--scenarios')
    ap.add_argument('--baseline')
    ap.add_argument('--candidates', nargs='*', default=[])
    ap.add_argument('--smoke', action='store_true')
    a = ap.parse_args()
    if a.smoke:
        smoke()
        return
    if not all((a.scenarios, a.baseline, a.candidates)):
        ap.error('--scenarios --baseline --candidates required')
    print(json.dumps(evaluate(a.scenarios, a.baseline, a.candidates), indent=2))


if __name__ == '__main__':
    main()
